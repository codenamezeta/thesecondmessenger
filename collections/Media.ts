import type { CollectionConfig } from 'payload'

/**
 * Media collection.
 *
 * Storage: Vercel Blob (configured via plugin in payload.config.ts).
 *
 * Optimization workflow:
 * - The original master file is uploaded as-is (no top-level `formatOptions`),
 *   so 3000x3000 album-art masters are preserved at full fidelity for
 *   downloads.
 * - At upload time, sharp generates a set of optimized derivatives
 *   (`sizes.thumbnail`, `sizes.card`, `sizes.feature`, `sizes.feature_avif`)
 *   in WebP/AVIF. The frontend reads `resource.sizes[name].url` via the
 *   `displaySize` prop on the `Media` / `ImageMedia` components.
 *
 * Backfill: existing uploads can be regenerated by hitting
 * `/api/admin/regenerate-media-sizes` while authenticated as an admin.
 */
export const Media: CollectionConfig = {
  slug: 'media',
  access: {
    read: () => true,
  },
  folders: true,
  fields: [
    {
      name: 'alt',
      type: 'text',
      required: false,
    },
  ],
  upload: {
    disableLocalStorage: true,
    mimeTypes: [
      'image/png',
      'image/jpeg',
      'image/webp',
      'image/avif',
      'image/svg+xml',
      'image/gif',
      'video/mp4',
      'video/webm',
      'video/quicktime',
    ],
    imageSizes: [
      {
        name: 'thumbnail',
        width: 400,
        height: 400,
        position: 'centre',
        formatOptions: { format: 'webp', options: { quality: 78 } },
      },
      {
        name: 'card',
        width: 800,
        height: 800,
        position: 'centre',
        formatOptions: { format: 'webp', options: { quality: 80 } },
      },
      {
        name: 'feature',
        width: 1600,
        height: 1600,
        position: 'centre',
        formatOptions: { format: 'webp', options: { quality: 82 } },
      },
      // AVIF only at the largest size — encoding is CPU-expensive at upload
      // time and the byte savings only become meaningful at larger dimensions.
      {
        name: 'feature_avif',
        width: 1600,
        height: 1600,
        position: 'centre',
        formatOptions: { format: 'avif', options: { quality: 55 } },
      },
    ],
  },
}
